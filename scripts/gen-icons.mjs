// Code generator: reads lucide-static SVGs and produces internal/web/icons_gen.go.
// Run: node scripts/gen-icons.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const iconsDir = join(root, "node_modules", "lucide-static", "icons");

const icons = [
	"arrow-left",
	"arrow-right",
	"rss",
	"list",
	"layout-grid",
	"external-link",
	"package-open",
	"x",
	"plus",
	"minus",
	"square-check",
	"circle-help",
	"bell",
	"bell-off",
	"package",
	"arrow-up-down",
	"arrow-down-a-z",
	"arrow-up-a-z",
	"info",
	"upload",
	"clipboard",
	"copy",
];

const entries = [];

for (const name of icons) {
	const svg = readFileSync(join(iconsDir, `${name}.svg`), "utf-8");
	// Extract inner content between <svg ...> and </svg>
	const match = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
	if (!match) {
		console.error(`Failed to parse ${name}.svg`);
		process.exit(1);
	}
	// Clean up inner content: trim, collapse whitespace, remove self-closing space
	const inner = match[1]
		.trim()
		.replace(/\n\s*/g, "")
		.replace(/ \/>/g, "/>");
	entries.push(`\t"${name}": \`${inner}\`,`);
}

const out = `// Code generated by scripts/gen-icons.mjs; DO NOT EDIT.
package web

var iconPaths = map[string]string{
${entries.join("\n")}
}
`;

const outPath = join(root, "internal", "web", "icons_gen.go");
writeFileSync(outPath, out);
console.log(`Generated ${outPath} with ${entries.length} icons.`);
